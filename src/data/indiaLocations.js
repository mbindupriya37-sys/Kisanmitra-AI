/**
 * Returns all verified States and Union Territories (36).
 */
export function getStates() {
  return Object.keys(INDIA_LOCATIONS).sort()
}

/**
 * Returns all verified official districts for a state.
 * Returns empty array if state is invalid or unselected.
 */
export function getDistrictsByState(state) {
  if (!state || !INDIA_LOCATIONS[state]) {
    return []
  }
  return Object.keys(INDIA_LOCATIONS[state]).sort()
}

/**
 * Returns verified sub-districts / talukas / major centers for a state and district.
 * Returns empty array if district is not found.
 */
export function getLocalitiesByDistrict(state, district) {
  if (!state || !district || !INDIA_LOCATIONS[state] || !INDIA_LOCATIONS[state][district]) {
    return []
  }
  return [...INDIA_LOCATIONS[state][district]].sort()
}
